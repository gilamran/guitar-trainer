export function iconSvg(name: string): string {
  const body = paths[name] ?? '';
  return `<svg viewBox="0 0 24 24" width="1em" height="1em" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${body}</svg>`;
}

/** Fills every `[data-icon]` element under `root`. */
export function renderIcons(root: ParentNode = document): void {
  root.querySelectorAll<HTMLElement>('[data-icon]').forEach((el) => {
    el.innerHTML = iconSvg(el.dataset.icon!);
  });
}

export function setIcon(el: HTMLElement, name: string): void {
  const slot = el.querySelector<HTMLElement>('[data-icon]') ?? el;
  slot.dataset.icon = name;
  slot.innerHTML = iconSvg(name);
}
